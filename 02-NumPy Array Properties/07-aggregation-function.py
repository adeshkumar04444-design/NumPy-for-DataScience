import numpy as np

arr = np.array([10, 20, 30, 40, 50])

# Sum of all elements
print(np.sum(arr))       # 150

# Minimum value
print(np.min(arr))       # 10

# Maximum value
print(np.max(arr))       # 50

# Average (mean) of all elements
print(np.mean(arr))      # 30.0

# Median value
print(np.median(arr))    # 30.0

# Standard deviation
print(np.std(arr))       # 14.142...

# Variance
print(np.var(arr))       # 200.0

# Product of all elements
print(np.prod(arr))      # 10000000
